import { describe, expect, it } from "vitest";
import { subtitleDisplayText } from "./subtitle-text";

describe("subtitleDisplayText：字幕显示的文字", () => {
  it.each([
    ["改了一处，另一处就会忘记改。", "改了一处 另一处就会忘记改", "句中逗号换空格，句末句号去掉"],
    ["同一件事写在两个地方，", "同一件事写在两个地方", "句末逗号去掉"],
    ["甲、乙；丙", "甲 乙 丙", "顿号、分号换空格"],
    ["第一条原则叫 DRY。", "第一条原则叫 DRY", "原有空格保留"],
    ["DRY， 是缩写", "DRY 是缩写", "标点旁已有空格时不出现两个空格"],
    ["好，，再来", "好 再来", "连续标点只留一个空格"],
    ["，开头", "开头", "句首标点去掉，不留开头空格"],
    ["真的吗？！", "真的吗？！", "保留问号叹号"],
    [
      "书名是《程序员修炼之道》（第二版）——经典：“DRY”和‘KISS’",
      "书名是《程序员修炼之道》（第二版）——经典：“DRY”和‘KISS’",
      "保留冒号、引号、书名号、括号、破折号",
    ],
    ["他说：“好的。”", "他说：“好的”", "引号前的句号直接去掉，不在引号前留空格"],
    ["（甲，乙。）后面", "（甲 乙）后面", "括号前的句号直接去掉"],
    ["没有标点", "没有标点", "没有标点时不变"],
  ])("%s → %s（%s）", (text, expected) => {
    expect(subtitleDisplayText(text)).toBe(expected);
  });
});
